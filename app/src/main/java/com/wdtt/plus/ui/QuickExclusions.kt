internal fun matchesQuickExclusionApp(name: String, packageName: String): Boolean {
    val packageLower = packageName.lowercase()
    if (packageLower in QuickExclusionExactPackages) return true
    val haystack = "$packageLower ${name.lowercase()}"
    return QuickExclusionKeywords.any(haystack::contains)
}
